#!/usr/bin/env node
/**
 * scripts/build-worker-main.mjs
 *
 * Recreates dist/server/worker-main.js after every `vite build`.
 * This file is the wrangler entry point — it wires the built TanStack
 * server with the Durable Object exports and queue/scheduled handlers
 * from the TypeScript source.
 *
 * Run automatically via the `build` script in package.json.
 */

import { writeFileSync, mkdirSync } from "fs";
import { resolve } from "path";

const outDir = resolve("dist/server");
mkdirSync(outDir, { recursive: true });

// Find the hashed router chunk name from dist/server/assets/
import { readdirSync } from "fs";
const assets = readdirSync(resolve("dist/server/assets"));
const routerChunk = assets.find((f) => f.startsWith("router-") && f.endsWith(".js"));
if (!routerChunk) {
  console.error("[build-worker-main] ERROR: No router-*.js chunk found in dist/server/assets/");
  process.exit(1);
}

const content = `// Auto-generated by scripts/build-worker-main.mjs — DO NOT EDIT MANUALLY.
// Re-run \`bun run build\` to regenerate.
import './assets/${routerChunk}';
import server from './server.js';
export { RateLimiterDO } from '../../src/lib/rate-limiter-do.ts';
export { CircuitStateDO } from '../../src/lib/server/circuit-breaker/circuit-breaker-do.ts';
import { processQueueBatch } from '../../src/lib/server/worker/consumer.ts';
import scheduledHandler from '../../src/routes/api.public.scheduled.ts';
import { flushLogs } from '../../src/lib/server-logger.ts';
export default {
  fetch: server.fetch.bind(server),
  async queue(batch, env, ctx) {
    await processQueueBatch(batch, env);
    ctx.waitUntil(flushLogs());
  },
  async scheduled(event, env, ctx) {
    await scheduledHandler.scheduled(event, env, ctx);
    ctx.waitUntil(flushLogs());
  },
};
`;

const outPath = resolve("dist/server/worker-main.js");
writeFileSync(outPath, content, "utf8");
console.log(`[build-worker-main] ✓ Wrote ${outPath} (using ${routerChunk})`);
